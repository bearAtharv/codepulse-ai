"""PR diff file filtering, hunk splitting, and LLM batching.

Implements Sections 3.2.2 and 3.2.3 of the architecture document:
- Filters binary files, lockfiles, vendored directories, generated files,
  unsupported languages, and oversized diffs (> 5,000 changed lines).
- Splits large file diffs at hunk boundaries so each chunk is <= 4,000 tokens.
- Extracts modified line numbers (1-indexed '+' lines) for diff-aware AST filtering.
- Batches chunks into groups of up to 8 chunks and <= 32,000 tokens for LLM calls.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field
from pathlib import PurePosixPath
from typing import Sequence

from codepulse.aggregation.line_mapping import parse_unified_diff
from codepulse.analysis.languages import detect_language
from codepulse.analysis.llm_engine import DiffChunk
from codepulse.ingestion.diff_fetcher import BaseDiffFetcher, PRFile

logger = logging.getLogger(__name__)

# ── Constants (Sections 3.2.2 & 3.2.3) ─────────────────────────────────

MAX_FILE_CHANGED_LINES: int = 5000
MAX_CHUNK_TOKENS: int = 4000
MAX_CHUNKS_PER_BATCH: int = 8
MAX_BATCH_TOKENS: int = 32000

LOCK_FILES: frozenset[str] = frozenset(
    {
        "package-lock.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "poetry.lock",
        "pipfile.lock",
        "cargo.lock",
        "go.sum",
        "composer.lock",
        "gemfile.lock",
    }
)

VENDORED_DIRS: frozenset[str] = frozenset(
    {
        "vendor",
        "node_modules",
        "third_party",
        "dist",
        "build",
        ".venv",
        "venv",
    }
)

GENERATED_MARKERS: tuple[str, ...] = (
    "// code generated",
    "# auto-generated",
    "/* auto-generated",
    "# generated by",
)

_HUNK_SPLIT_RE = re.compile(r"(?=^@@\s+-\d+(?:,\d+)?\s+\+\d+(?:,\d+)?\s+@@)", re.MULTILINE)


# ── Models ─────────────────────────────────────────────────────────────


@dataclass
class AnalysisChunk:
    """Self-contained unit of code and diff for AST and LLM analysis."""

    file_path: str
    language: str
    source_code: str
    diff_text: str
    hunk_header: str
    modified_lines: list[int] = field(default_factory=list)
    estimated_tokens: int = 0

    def to_diff_chunk(self) -> DiffChunk:
        """Convert to LLM engine DiffChunk."""
        return DiffChunk(
            file_path=self.file_path,
            hunk_header=self.hunk_header,
            content=self.diff_text,
        )

    def to_dict(self) -> dict:
        """Serialize for Celery task transport."""
        return {
            "file_path": self.file_path,
            "language": self.language,
            "source_code": self.source_code,
            "diff_text": self.diff_text,
            "hunk_header": self.hunk_header,
            "modified_lines": self.modified_lines,
            "estimated_tokens": self.estimated_tokens,
        }

    @classmethod
    def from_dict(cls, data: dict) -> AnalysisChunk:
        """Deserialize from Celery task transport."""
        return cls(
            file_path=data["file_path"],
            language=data["language"],
            source_code=data["source_code"],
            diff_text=data["diff_text"],
            hunk_header=data["hunk_header"],
            modified_lines=list(data.get("modified_lines", [])),
            estimated_tokens=int(data.get("estimated_tokens", 0)),
        )


@dataclass
class PreprocessResult:
    """Output of preprocessing and chunking a PR diff."""

    chunks: list[AnalysisChunk] = field(default_factory=list)
    llm_batches: list[list[AnalysisChunk]] = field(default_factory=list)
    unified_diff: str = ""
    files_analyzed: int = 0
    filtered_files: dict[str, str] = field(default_factory=dict)
    oversized_files: list[str] = field(default_factory=list)


# ── File Filtering (Section 3.2.2) ─────────────────────────────────────


def estimate_tokens(text: str) -> int:
    """Estimate token count (~4 characters per token)."""
    return max(1, len(text) // 4) if text else 0


def _is_generated_code(content_or_patch: str) -> bool:
    """Check if the first 5 lines contain generated-code markers (§3.2.2)."""
    lines: list[str] = []
    for raw_line in content_or_patch.splitlines():
        if raw_line.startswith(("@@", "---", "+++")):
            continue
        cleaned = raw_line[1:] if raw_line.startswith(("+", " ")) else raw_line
        lines.append(cleaned.strip().lower())
        if len(lines) >= 5:
            break

    first_five = "\n".join(lines)
    return any(marker in first_five for marker in GENERATED_MARKERS)


def should_filter_file(pr_file: PRFile) -> str | None:
    """Return filter reason string if file should be excluded, else None."""
    path = PurePosixPath(pr_file.filename)

    if pr_file.status == "removed":
        return "removed"

    # 1. Lock files
    if path.name.lower() in LOCK_FILES:
        return "lockfile"

    # 2. Vendored directories
    if any(part.lower() in VENDORED_DIRS for part in path.parts[:-1]):
        return "vendored"

    # 3. Binary / missing patch
    if not pr_file.patch:
        return "binary_or_empty_patch"

    # 4. Unsupported language extension
    if detect_language(pr_file.filename) is None:
        return "unsupported_language"

    # 5. Diff-size threshold (> 5,000 changed lines)
    changed_lines = pr_file.changes or (pr_file.additions + pr_file.deletions)
    if changed_lines > MAX_FILE_CHANGED_LINES:
        return "oversized"

    # 6. Generated code markers in first 5 lines
    sample = pr_file.raw_content or pr_file.patch
    if _is_generated_code(sample):
        return "generated"

    return None


# ── Chunking & Batching (Section 3.2.3) ────────────────────────────────


def _reconstruct_source_from_patch(patch: str) -> str:
    """Fallback reconstruction of new-file lines from a unified diff patch."""
    lines: list[str] = []
    for line in patch.splitlines():
        if line.startswith(("@@", "---", "+++")):
            continue
        if line.startswith("+") or line.startswith(" "):
            lines.append(line[1:])
    return "\n".join(lines) + ("\n" if lines else "")


def split_patch_into_subpatches(
    patch: str,
    max_tokens: int = MAX_CHUNK_TOKENS,
) -> list[tuple[str, str]]:
    """Split a file patch at hunk boundaries so each chunk is <= max_tokens.

    Returns:
        List of (hunk_header, patch_text) tuples.
    """
    raw_hunks = [h for h in _HUNK_SPLIT_RE.split(patch.strip()) if h.strip()]
    if not raw_hunks:
        return [("@@ -1,1 +1,1 @@", patch)]

    # If the entire patch fits in one chunk, keep it together
    if estimate_tokens(patch) <= max_tokens:
        first_header = raw_hunks[0].splitlines()[0].strip()
        return [(first_header, patch)]

    subpatches: list[tuple[str, str]] = []
    current_hunks: list[str] = []
    current_tokens = 0
    current_header = ""

    for hunk in raw_hunks:
        hunk_tokens = estimate_tokens(hunk)
        header_line = hunk.splitlines()[0].strip()
        if not current_hunks:
            current_header = header_line
            current_hunks.append(hunk)
            current_tokens = hunk_tokens
        elif current_tokens + hunk_tokens <= max_tokens:
            current_hunks.append(hunk)
            current_tokens += hunk_tokens
        else:
            subpatches.append((current_header, "\n".join(current_hunks)))
            current_header = header_line
            current_hunks = [hunk]
            current_tokens = hunk_tokens

    if current_hunks:
        subpatches.append((current_header, "\n".join(current_hunks)))

    return subpatches


def batch_chunks_for_llm(
    chunks: Sequence[AnalysisChunk],
    max_chunks: int = MAX_CHUNKS_PER_BATCH,
    max_tokens: int = MAX_BATCH_TOKENS,
) -> list[list[AnalysisChunk]]:
    """Group chunks into batches of <= 8 chunks and <= 32,000 tokens (§3.2.3)."""
    batches: list[list[AnalysisChunk]] = []
    current_batch: list[AnalysisChunk] = []
    current_tokens = 0

    for chunk in chunks:
        chunk_tokens = chunk.estimated_tokens or estimate_tokens(chunk.diff_text)
        if current_batch and (
            len(current_batch) >= max_chunks or current_tokens + chunk_tokens > max_tokens
        ):
            batches.append(current_batch)
            current_batch = [chunk]
            current_tokens = chunk_tokens
        else:
            current_batch.append(chunk)
            current_tokens += chunk_tokens

    if current_batch:
        batches.append(current_batch)

    return batches


def preprocess_pr_files(
    pr_files: Sequence[PRFile],
    *,
    owner: str = "",
    repo: str = "",
    head_sha: str = "",
    installation_id: int | None = None,
    diff_fetcher: BaseDiffFetcher | None = None,
    max_chunk_tokens: int = MAX_CHUNK_TOKENS,
) -> PreprocessResult:
    """Filter PR files, extract modified lines, split into chunks, and batch for LLM."""
    result = PreprocessResult()
    unified_diff_parts: list[str] = []

    for pr_file in pr_files:
        reason = should_filter_file(pr_file)
        if reason is not None:
            result.filtered_files[pr_file.filename] = reason
            if reason == "oversized":
                result.oversized_files.append(pr_file.filename)
            logger.debug("Filtered file %s: %s", pr_file.filename, reason)
            continue

        lang = detect_language(pr_file.filename)
        assert lang is not None  # Checked in should_filter_file
        assert pr_file.patch is not None

        # Format complete unified diff entry for this file
        file_unified_diff = (
            f"--- a/{pr_file.filename}\n"
            f"+++ b/{pr_file.filename}\n"
            f"{pr_file.patch.rstrip()}\n"
        )
        unified_diff_parts.append(file_unified_diff)
        result.files_analyzed += 1

        # Resolve full file content for AST parsing
        source_code = pr_file.raw_content
        if source_code is None and diff_fetcher is not None and owner and repo and head_sha:
            source_code = diff_fetcher.fetch_file_content(
                owner, repo, pr_file.filename, head_sha, installation_id
            )
        if not source_code:
            source_code = _reconstruct_source_from_patch(pr_file.patch)

        # Split into subpatches if oversized (> 4,000 tokens)
        subpatches = split_patch_into_subpatches(pr_file.patch, max_tokens=max_chunk_tokens)
        for hunk_header, subpatch in subpatches:
            sub_unified = (
                f"--- a/{pr_file.filename}\n"
                f"+++ b/{pr_file.filename}\n"
                f"{subpatch.rstrip()}\n"
            )
            parsed = parse_unified_diff(sub_unified)
            file_diff = parsed.get(pr_file.filename)
            mod_lines: set[int] = set()
            if file_diff:
                for h in file_diff.hunks:
                    mod_lines.update(h.modified_lines)

            chunk = AnalysisChunk(
                file_path=pr_file.filename,
                language=lang,
                source_code=source_code,
                diff_text=subpatch,
                hunk_header=hunk_header,
                modified_lines=sorted(mod_lines),
                estimated_tokens=estimate_tokens(subpatch),
            )
            result.chunks.append(chunk)

    result.unified_diff = "\n".join(unified_diff_parts)
    result.llm_batches = batch_chunks_for_llm(result.chunks)
    return result
